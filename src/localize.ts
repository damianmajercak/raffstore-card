const LANGS: Record<string, Strings> = { en, sk, cs };

export type StringKey = keyof Strings;

export function localize(language: string | undefined, key: StringKey): string {
  const lang = (language ?? "en").split("-")[0].toLowerCase();
  return (LANGS[lang] ?? en)[key] ?? en[key];
}
